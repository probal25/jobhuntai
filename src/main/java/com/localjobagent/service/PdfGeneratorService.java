package com.localjobagent.service;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;

import java.io.*;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.*;
import java.util.UUID;

/**
 * PDF GENERATOR SERVICE
 *
 * Handles the conversion of tailored resume content into a professional PDF
 * by injecting content into a LaTeX template and compiling it via pdflatex.
 */
@Service
public class PdfGeneratorService {

    private static final Logger log = LoggerFactory.getLogger(PdfGeneratorService.class);
    private static final String TEMPLATE_PATH = "src/main/resources/master-resume.tex";
    private static final String OUTPUT_DIR = "generated_resumes/";
    private static final String PDFLATEX_PATH = "/Library/TeX/texbin/pdflatex";

    public PdfGeneratorService() {
        try {
            Files.createDirectories(Paths.get(OUTPUT_DIR));
        } catch (IOException e) {
            log.error("Could not create output directory: {}", e.getMessage());
        }
    }

    /**
     * Generates a tailored PDF resume.
     *
     * @param tailoredContent The content generated by the ResumeAdapterAgent
     * @return Path to the generated PDF file
     */
    public Path generatePdf(String tailoredContent) {
        String requestId = UUID.randomUUID().toString();
        // Use absolute paths to avoid any ambiguity with the working directory
        Path absoluteOutputDir = Paths.get(OUTPUT_DIR).toAbsolutePath();
        Path texFile = absoluteOutputDir.resolve(requestId + ".tex");
        Path pdfFile = absoluteOutputDir.resolve(requestId + ".pdf");

        try {
            // 1. Read the master template
            String template = Files.readString(Paths.get(TEMPLATE_PATH), StandardCharsets.UTF_8);

            // 2. Inject the tailored content
            String processedTex = injectContent(template, tailoredContent);
            Files.writeString(texFile, processedTex, StandardCharsets.UTF_8);

            // 3. Compile using pdflatex
            // Use absolute path for the input file
            String absoluteTexPath = texFile.toAbsolutePath().toString();

            // We run pdflatex twice to resolve references/formatting
            executeCommandWithPath("-interaction=nonstopmode", "-output-directory=" + absoluteOutputDir.toString(), absoluteTexPath);
            executeCommandWithPath("-interaction=nonstopmode", "-output-directory=" + absoluteOutputDir.toString(), absoluteTexPath);

            // 4. Cleanup .log, .aux files
            cleanupLatexFiles(requestId);

            log.info("PdfGenerator: successfully generated PDF at {}", pdfFile);
            return pdfFile;

        } catch (Exception e) {
            log.error("PdfGenerator: failed to generate PDF - {}", e.getMessage());
            return null;
        }
    }

    private String injectContent(String template, String tailoredContent) {
        // Sanitize the content to prevent LaTeX compilation errors
        String sanitizedContent = sanitizeLatex(tailoredContent);

        if (sanitizedContent.contains("\\section")) {
            // If the LLM provided LaTeX, we replace the main body
            return template.replaceAll("(?s)%-----------SUMMARY-----------\\n.*\\resumeSubHeadingListEnd\\n\\n%-----------EXPERIENCE-----------------.*\\resumeSubHeadingListEnd", sanitizedContent);
        } else {
            // Fallback: just wrap the text in a basic LaTeX block
            String fallback = "\\section{Tailored Summary}\n\\resumeSubHeadingListStart\n\\text{" + sanitizedContent + "}\n\\resumeSubHeadingListEnd";
            return template.replace("\\section{Summary}", fallback);
        }
    }

    private String sanitizeLatex(String text) {
        if (text == null) return "";
        return text.replace("&", "\\&")
                   .replace("%", "\\%")
                   .replace("$", "\\$")
                   .replace("#", "\\#")
                   .replace("_", "\\_")
                   .replace("{", "\\{")
                   .replace("}", "\\}")
                   .replace("~", "\\textasciitilde{}")
                   .replace("^", "\\textasciicircum{}");
    }

    private void executeCommand(String... command) throws IOException, InterruptedException {
        ProcessBuilder pb = new ProcessBuilder(command);
        pb.redirectErrorStream(true);
        Process process = pb.start();

        try (BufferedReader reader = new BufferedReader(new InputStreamReader(process.getInputStream()))) {
            while (reader.readLine() != null) { /* consume output */ }
        }

        int exitCode = process.waitFor();
        if (exitCode != 0) {
            throw new IOException("Command failed with exit code " + exitCode);
        }
    }

    private void executeCommandWithPath(String... args) throws IOException, InterruptedException {
        List<String> fullCommand = new ArrayList<>();
        fullCommand.add(PDFLATEX_PATH);
        fullCommand.addAll(Arrays.asList(args));

        log.info("Executing LaTeX command: {}", String.join(" ", fullCommand));

        ProcessBuilder pb = new ProcessBuilder(fullCommand);
        pb.directory(new File(OUTPUT_DIR));
        pb.redirectErrorStream(true);
        Process process = pb.start();

        StringBuilder output = new StringBuilder();
        try (BufferedReader reader = new BufferedReader(new InputStreamReader(process.getInputStream()))) {
            String line;
            while ((line = reader.readLine()) != null) {
                output.append(line).append("\n");
            }
        }

        int exitCode = process.waitFor();
        if (exitCode != 0) {
            log.error("pdflatex failed with exit code {}. Output:\n{}", exitCode, output);
            throw new IOException("pdflatex failed with exit code " + exitCode);
        }
    }

    private void cleanupLatexFiles(String requestId) {
        String[] extensions = {".log", ".aux", ".out"};
        for (String ext : extensions) {
            try {
                Files.deleteIfExists(Paths.get(OUTPUT_DIR + requestId + ext));
            } catch (IOException ignored) {}
        }
    }
}
